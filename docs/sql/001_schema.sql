-- Acme Portal — DDL de referência.
-- Aplicar SEMPRE pelo MCP do Supabase, no projeto "Supabase do portal" (<project-ref>).
-- Regra: apenas objetos com prefixo acme_. Nada fora disso pode ser lido ou alterado.

-- ---------------------------------------------------------------------------
-- 1. Perfis
-- ---------------------------------------------------------------------------
create table if not exists public.acme_profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('colaborador', 'atendente')),
  category text check (category in ('ti', 'rh')),
  display_name text not null,
  created_at timestamptz not null default now(),
  constraint acme_profiles_category_by_role check (
    (role = 'colaborador' and category is null)
    or (role = 'atendente' and category is not null)
  )
);

alter table public.acme_profiles enable row level security;

-- ---------------------------------------------------------------------------
-- 2. Chamados
-- ---------------------------------------------------------------------------
create table if not exists public.acme_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  category text not null check (category in ('ti', 'rh')),
  title text not null check (char_length(title) between 5 and 120),
  description text not null check (char_length(description) between 10 and 4000),
  status text not null default 'aberto'
    check (status in ('aberto', 'em_andamento', 'respondido', 'fechado')),
  answer text check (answer is null or char_length(answer) between 1 and 4000),
  answered_at timestamptz,
  created_at timestamptz not null default now(),
  constraint acme_tickets_answer_required check (
    status not in ('respondido', 'fechado') or answer is not null
  )
);

create index if not exists acme_tickets_user_idx on public.acme_tickets (user_id, created_at desc);
create index if not exists acme_tickets_category_status_idx on public.acme_tickets (category, status, created_at desc);

alter table public.acme_tickets enable row level security;

-- ---------------------------------------------------------------------------
-- 3. Contador diário do chat (10 perguntas/dia, America/Sao_Paulo)
-- ---------------------------------------------------------------------------
create table if not exists public.acme_chat_usage (
  user_id uuid not null references auth.users (id) on delete cascade,
  day date not null,
  count integer not null default 0 check (count >= 0),
  primary key (user_id, day)
);

alter table public.acme_chat_usage enable row level security;
-- Sem policy: tabela acessível apenas pela função security definer abaixo.

-- ---------------------------------------------------------------------------
-- 4. Base vetorial (pgvector já instalado em extensions)
-- ---------------------------------------------------------------------------
create table if not exists public.acme_documents_vec (
  id bigint generated by default as identity primary key,
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  embedding extensions.vector(1536) not null
);

create index if not exists acme_documents_vec_embedding_idx
  on public.acme_documents_vec using hnsw (embedding extensions.vector_cosine_ops);

alter table public.acme_documents_vec enable row level security;
-- Sem policy: acessível apenas por service_role (n8n).
revoke all on public.acme_documents_vec from anon, authenticated;

-- ---------------------------------------------------------------------------
-- 5. Helpers de autorização (security definer para evitar recursão de RLS)
-- ---------------------------------------------------------------------------
create or replace function public.acme_current_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.acme_profiles where id = (select auth.uid());
$$;

create or replace function public.acme_current_category()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select category from public.acme_profiles where id = (select auth.uid());
$$;

revoke all on function public.acme_current_role() from public, anon;
revoke all on function public.acme_current_category() from public, anon;
grant execute on function public.acme_current_role() to authenticated;
grant execute on function public.acme_current_category() to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Consumo atômico de pergunta (recusa a 11ª)
-- ---------------------------------------------------------------------------
create or replace function public.acme_consume_question()
returns table (used integer, remaining integer, allowed boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_day date := (now() at time zone 'America/Sao_Paulo')::date;
  v_count integer;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  insert into public.acme_chat_usage (user_id, day, count)
  values (v_uid, v_day, 1)
  on conflict (user_id, day) do update
    set count = public.acme_chat_usage.count + 1
    where public.acme_chat_usage.count < 10
  returning count into v_count;

  if v_count is null then
    select c.count into v_count
    from public.acme_chat_usage c
    where c.user_id = v_uid and c.day = v_day;

    return query select v_count, 0, false;
  end if;

  return query select v_count, 10 - v_count, true;
end;
$$;

revoke all on function public.acme_consume_question() from public, anon;
grant execute on function public.acme_consume_question() to authenticated;

-- ---------------------------------------------------------------------------
-- 6.1 Leitura do contador do dia (para a interface)
-- ---------------------------------------------------------------------------
create or replace function public.acme_question_status(p_day date)
returns table (used integer, remaining integer)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_used integer := 0;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  select c.count into v_used
  from public.acme_chat_usage c
  where c.user_id = v_uid and c.day = p_day;

  return query
    select coalesce(v_used, 0) as used,
           greatest(10 - coalesce(v_used, 0), 0) as remaining;
end;
$$;

revoke all on function public.acme_question_status(date) from public, anon;
grant execute on function public.acme_question_status(date) to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Fechamento do chamado pelo colaborador (respondido -> fechado)
-- ---------------------------------------------------------------------------create or replace function public.acme_close_ticket(p_ticket_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_status text;
  v_owner uuid;
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  select status, user_id into v_status, v_owner
  from public.acme_tickets
  where id = p_ticket_id;

  if v_owner is null then
    raise exception 'ticket not found' using errcode = 'P0002';
  end if;

  if v_owner <> v_uid then
    raise exception 'not allowed' using errcode = '42501';
  end if;

  if v_status <> 'respondido' then
    raise exception 'ticket is not answered' using errcode = '22000';
  end if;

  update public.acme_tickets
  set status = 'fechado'
  where id = p_ticket_id;
end;
$$;

revoke all on function public.acme_close_ticket(uuid) from public, anon;
grant execute on function public.acme_close_ticket(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. Busca vetorial (nome próprio: match_documents colidiria no banco compartilhado)
-- ---------------------------------------------------------------------------
create or replace function public.acme_match_documents(
  query_embedding extensions.vector(1536),
  match_count integer default 4,
  filter jsonb default '{}'::jsonb
)
returns table (id bigint, content text, metadata jsonb, similarity double precision)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select d.id,
         d.content,
         d.metadata,
         1 - (d.embedding <=> query_embedding) as similarity
  from public.acme_documents_vec d
  where d.metadata @> filter
  order by d.embedding <=> query_embedding
  limit greatest(match_count, 1);
$$;

revoke all on function public.acme_match_documents(extensions.vector, integer, jsonb) from public, anon, authenticated;
grant execute on function public.acme_match_documents(extensions.vector, integer, jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- 9. Políticas de acesso
-- ---------------------------------------------------------------------------

-- Perfil: cada um lê o próprio; atendente lê o perfil de quem abriu chamado na sua categoria.
create policy acme_profiles_select on public.acme_profiles
for select to authenticated
using (
  id = (select auth.uid())
  or (
    public.acme_current_role() = 'atendente'
    and exists (
      select 1 from public.acme_tickets t
      where t.user_id = acme_profiles.id
        and t.category = public.acme_current_category()
    )
  )
);

-- Chamados: colaborador vê os seus; atendente vê os da sua categoria.
create policy acme_tickets_select on public.acme_tickets
for select to authenticated
using (
  user_id = (select auth.uid())
  or (
    public.acme_current_role() = 'atendente'
    and category = public.acme_current_category()
  )
);

-- Chamados: só o colaborador abre, sempre em seu próprio nome.
create policy acme_tickets_insert on public.acme_tickets
for insert to authenticated
with check (
  user_id = (select auth.uid())
  and public.acme_current_role() = 'colaborador'
);

-- Chamados: só o atendente da categoria atualiza (assumir/responder).
-- O fechamento pelo colaborador passa pela função acme_close_ticket.
-- Um chamado fechado não pode ser reaberto pelo atendente (RF-15), e o
-- atendente só o leva para em_andamento ou respondido.
create policy acme_tickets_update on public.acme_tickets
for update to authenticated
using (
  public.acme_current_role() = 'atendente'
  and category = public.acme_current_category()
  and status <> 'fechado'
)
with check (
  public.acme_current_role() = 'atendente'
  and category = public.acme_current_category()
  and status in ('em_andamento', 'respondido')
);

-- ---------------------------------------------------------------------------
-- 10. Grants: o RLS filtra linhas, não colunas; aqui fica o resto
-- ---------------------------------------------------------------------------

-- Chamados: o atendente muda status, resposta e data da resposta — nunca o
-- dono, a categoria, o título ou a descrição da linha.
revoke insert, update, delete on public.acme_tickets from anon;
revoke delete on public.acme_tickets from authenticated;
revoke update on public.acme_tickets from authenticated;
grant update (status, answer, answered_at) on public.acme_tickets to authenticated;

-- Perfis: escritos só pelo servidor (seed/migração), nunca pelo cliente.
revoke insert, update, delete on public.acme_profiles from anon, authenticated;

-- Contador diário: nenhum acesso direto, só pela função security definer.
revoke all on public.acme_chat_usage from anon, authenticated;

-- O Supabase concede ALL por padrão em tabelas novas do schema public; estes
-- privilégios não fazem sentido aqui (role anônimo não tem policy nenhuma, e
-- TRUNCATE não passa por RLS).
revoke all on public.acme_profiles, public.acme_tickets from anon;
revoke truncate, references, trigger on public.acme_profiles, public.acme_tickets from authenticated;
